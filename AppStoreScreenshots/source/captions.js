// Fonts and type settings per script. Tight negative tracking breaks Arabic joining and
// Devanagari conjuncts and crowds CJK, so those use normal tracking.
window.wgApplyLangStyle = function (lang) {
  const FONTS = { ja: '"Hiragino Sans", "Hiragino Kaku Gothic ProN"', ko: '"Apple SD Gothic Neo"',
                  ar: '"SF Arabic", "Geeza Pro"', hi: '"Kohinoor Devanagari"' };
  const HTML_LANG = { fr: "fr", ja: "ja", ko: "ko", ru: "ru", ar: "ar", hi: "hi" };
  if (!HTML_LANG[lang]) return;
  document.documentElement.lang = HTML_LANG[lang];
  let css = "";
  if (FONTS[lang]) css += `body { font-family: ${FONTS[lang]}, -apple-system, sans-serif; }
    h1 { letter-spacing: 0; font-weight: 700; line-height: 1.12; } .eyebrow { letter-spacing: .02em; }`;
  if (lang === "ar") css += `.copy { direction: rtl; } h1 { line-height: 1.25; }`;
  if (lang === "hi") css += `h1 { line-height: 1.25; }`;
  document.head.insertAdjacentHTML("beforeend", `<style>${css}</style>`);
};

// Shrink a headline until it takes no more lines than it was written with.
window.wgFitTitle = function (h1) {
  const lines = (h1.innerHTML.match(/<br>/g) || []).length + 1;
  let size = parseFloat(getComputedStyle(h1).fontSize);
  const lh = () => parseFloat(getComputedStyle(h1).lineHeight) || size * 1.1;
  while (h1.getBoundingClientRect().height > lines * lh() * 1.08 && size > 40) {
    size -= 4; h1.style.fontSize = size + "px";
  }
};
